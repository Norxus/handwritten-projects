# 通常 __init__.py 还可能承担这些职责：

# - 让 vector_stores 成为一个可导入的包 ，这是一种约定，明确告诉人和 Python：这是一个包，同时给这个包一个统一的对外入口
# - 统一导出子模块中的公共 API，让外部觉得这个目录本身就是一个“统一入口”，外部导入的时候不用再精确到文件了
# - 在包加载时做少量初始化，比如注册一些后端实现，但一般不建议在这里写太重的逻辑
# - 定义包级别常量或版本信息，也就是把整个包共享的配置放在这里
# - 控制 from xxx import * 的导出范围，对包来说，外部写 from mem0.vector_stores import * 时，Python 实际上看的是 init .py 暴露了什么
